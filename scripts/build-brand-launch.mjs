#!/usr/bin/env node
/**
 * THE iOS LAUNCH IMAGES (10 November 2026).
 *
 * With no `apple-touch-startup-image`, an installed iPhone web app shows its own
 * blank snapshot between the tap and the first page, which is the long empty
 * navy screen the founder filmed. These images put the bright mark on the brand
 * ground there instead, drawn to match the opening screen the page paints from
 * its first frame (components/startup/OpeningScreen.tsx: the same ground, the mark at
 * 36 per cent of the width, centred at 46 per cent of the height), so the hand
 * from iOS's snapshot to the page does not move.
 *
 * Run from the repository root:   node scripts/build-brand-launch.mjs
 * Writes apps/web/public/pwa/launch/launch-<w>x<h>.png and a manifest of the
 * media queries the page links (apps/web/src/lib/brand/launch-images.ts).
 * Also lifts the palette in the animated launch artwork (public/brand/launch/*.svg)
 * to the refreshed one, since those files carry their own copies of the colours.
 */
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

import { markSvg, MARK_VIEWBOX } from "./brand/logo-art.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const WEB = path.join(ROOT, "apps/web");
const OUT = path.join(WEB, "public/pwa/launch");

/* The page paints this ground from tokens: the brand blue at 24 per cent mixed into
   --nf-surface-artwork (#010118), which is #011A4F; the two must stay one colour. */
export const GROUND = { base: "#010118", glow: "#011A4F", cx: 0.5, cy: 0.44, r: 0.62 };
export const MARK_WIDTH = 0.36;
export const MARK_CENTRE_Y = 0.46;

/** [css width, css height, pixel ratio], portrait. */
const DEVICES = [
  [440, 956, 3],
  [402, 874, 3],
  [393, 852, 3],
  [390, 844, 3],
  [430, 932, 3],
];

const mark = markSvg();
const aspect = MARK_VIEWBOX.w / MARK_VIEWBOX.h;
const entries = [];
for (const [cw, ch, ratio] of DEVICES) {
  const W = cw * ratio;
  const H = ch * ratio;
  const mw = Math.round(W * MARK_WIDTH);
  const mh = Math.round(mw / aspect);
  const density = Math.max(72, Math.ceil((72 * mw * 2) / MARK_VIEWBOX.w));
  const markPng = await sharp(Buffer.from(mark), { density }).resize({ width: mw, kernel: "lanczos3" }).png().toBuffer();
  const ground = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}"><defs><radialGradient id="g" cx="${GROUND.cx}" cy="${GROUND.cy}" r="${GROUND.r}"><stop offset="0" stop-color="${GROUND.glow}"/><stop offset="1" stop-color="${GROUND.base}"/></radialGradient></defs><rect width="${W}" height="${H}" fill="url(#g)"/></svg>`,
  );
  const buf = await sharp(ground)
    .composite([{ input: markPng, left: Math.round((W - mw) / 2), top: Math.round(H * MARK_CENTRE_Y - mh / 2) }])
    .removeAlpha()
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toBuffer();
  const file = `launch-${W}x${H}.png`;
  await mkdir(OUT, { recursive: true });
  await writeFile(path.join(OUT, file), buf);
  entries.push({ file, width: W, height: H, cssWidth: cw, cssHeight: ch, ratio });
  console.log(file, `${Math.round((await stat(path.join(OUT, file))).size / 1024)}kB`);
}

const body = [
  "/**",
  " * GENERATED by `node scripts/build-brand-launch.mjs`. Do not hand edit.",
  " * The iOS launch images and the media query each one answers.",
  " */",
  "",
  "export const LAUNCH_IMAGES = [",
  ...entries.map(
    (e) =>
      `  { url: "/pwa/launch/${e.file}", width: ${e.width}, height: ${e.height}, media: "(device-width: ${e.cssWidth}px) and (device-height: ${e.cssHeight}px) and (-webkit-device-pixel-ratio: ${e.ratio}) and (orientation: portrait)" },`,
  ),
  "] as const;",
  "",
].join("\n");
await writeFile(path.join(WEB, "src/lib/brand/launch-images.ts"), body);

/* The animated launch artwork carries its own copy of the old palette. */
const LIFT = [
  ["#3FDCFF", "#5BE7FF"],
  ["#1C86FF", "#2F95FF"],
  ["#1A4CF0", "#2F6BFF"],
  ["#1238C8", "#2455F2"],
  ["#0B2A9E", "#1D47D8"],
  ["#FFA04A", "#FFB25E"],
  ["#FF8A3C", "#FF9244"],
  ["#F2561E", "#F96B28"],
];
for (const name of ["vallo-launch.svg", "vallo-launch-still.svg", "vallo-mark-draw.svg"]) {
  const file = path.join(WEB, "public/brand/launch", name);
  let text = await readFile(file, "utf8");
  for (const [from, to] of LIFT) text = text.split(from).join(to).split(from.toLowerCase()).join(to);
  await writeFile(file, text);
}
console.log("launch artwork palette lifted");

/*
 * THE OPENING SCREEN'S ANIMATED ARTWORK, INLINE (the founder, 11 November 2026:
 * "it was built and I was the one who said it should be built").
 *
 * `vallo-launch.svg` already draws the whole sequence: the ring sweeps round,
 * the four towers rise, the mark travels to its place and the five letters of
 * the wordmark slide out from behind it. It carried that choreography in its
 * own `<style>` element, which is why it could only ever be used as an image.
 *
 * The opening screen must be in the FIRST HTML, with no request, so the mark is
 * in frame one. Inlining the file as it stands would put a `<style>` element in
 * the document, and the Content Security Policy allows none (style-src-elem is
 * 'self', and a test holds it there): the browser would drop the block and the
 * artwork would arrive with every piece already in its final place, animating
 * nothing. So the element is stripped here and the identical rules live in
 * `open.css`, scoped under `.nf-open__launch`, where they are served from a
 * stylesheet the policy already allows. The class names on the shapes are the
 * file's own and the two must move together.
 */
const launchSvg = (await readFile(path.join(WEB, "public/brand/launch/vallo-launch.svg"), "utf8"))
  .replace(/<style[^>]*>[\s\S]*?<\/style>/g, "")
  .replace(/\s+/g, " ")
  .trim();
if (/<style/.test(launchSvg)) throw new Error("the opening artwork still carries a style element");
for (const needed of ["sw", "mv", "t t0", "t t3", "l l0", "l l4"]) {
  if (!launchSvg.includes(`class="${needed}"`)) throw new Error(`the opening artwork lost class ${needed}`);
}
await writeFile(
  path.join(WEB, "src/components/startup/open-launch.generated.ts"),
  [
    "/**",
    " * GENERATED by `node scripts/build-brand-launch.mjs`. Do not hand edit.",
    " * The animated opening artwork (the mark and the wordmark) as one inline SVG",
    " * string, with its own `<style>` removed: the choreography lives in",
    " * `open.css` instead, because the policy allows no style element. The class",
    " * names below are what that sheet animates.",
    " */",
    "/* eslint-disable nf/no-raw-colour -- the logo artwork's own palette, generated */",
    "",
    `export const OPEN_LAUNCH_SVG = ${JSON.stringify(launchSvg)};`,
    "",
  ].join("\n"),
);
console.log("opening artwork inlined", Math.round(launchSvg.length / 1024) + "kB");
