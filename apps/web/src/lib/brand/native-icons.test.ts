import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import sharp from "sharp";

/**
 * THE NATIVE STORE ICONS (10 November 2026, brand refresh part 2). Read from
 * the PNG headers and the pixels, not trusted from file names: every launcher
 * icon at the size its density needs, the iOS marketing icon with no alpha
 * channel and square corners, the Android adaptive foreground inside the safe
 * zone over a bright full-bleed background, and the notification glyph as
 * white on transparent. Regenerated by `BRAND_ONLY_NATIVE=1 node
 * scripts/build-brand-logo.mjs`; nothing on a device changes until a new
 * TestFlight or Play build ships.
 */
const WEB = join(__dirname, "..", "..", "..");
const RES = join(WEB, "android/app/src/main/res");
const APPICON = join(WEB, "ios/App/App/Assets.xcassets/AppIcon.appiconset");

function header(file: string): { w: number; h: number; colourType: number } {
  const b = readFileSync(file);
  expect(b.subarray(0, 8).toString("hex"), file).toBe("89504e470d0a1a0a");
  expect(b.subarray(12, 16).toString("ascii")).toBe("IHDR");
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20), colourType: b[25]! };
}

const DENSITY: Record<string, number> = { ldpi: 36, mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

describe("iOS AppIcon", () => {
  const contents = JSON.parse(readFileSync(join(APPICON, "Contents.json"), "utf8")) as { images: { filename: string; size: string }[] };

  it("Contents.json still names the one 1024 marketing icon, and the file is exactly that size", () => {
    expect(contents.images).toHaveLength(1);
    const [image] = contents.images;
    expect(image).toMatchObject({ size: "1024x1024", filename: "AppIcon-512@2x.png" });
    expect(header(join(APPICON, image!.filename))).toMatchObject({ w: 1024, h: 1024 });
  });

  it("has NO alpha channel (colour type 2, plain RGB) and no rounded corners: the corner pixels are the tile", async () => {
    const file = join(APPICON, contents.images[0]!.filename);
    expect(header(file).colourType).toBe(2);
    const { data, info } = await sharp(file).raw().toBuffer({ resolveWithObject: true });
    expect(info.channels).toBe(3);
    const at = (x: number, y: number) => [0, 1, 2].map((c) => data[(y * info.width + x) * 3 + c]!);
    for (const [x, y] of [[0, 0], [1023, 0], [0, 1023], [1023, 1023]] as const) {
      const [r, g, b] = at(x, y);
      /* The bright ground: near white at the top, pale blue at the foot. Never navy, never a cut-away corner. */
      expect(Math.min(r!, g!, b!)).toBeGreaterThan(200);
    }
  });
});

describe("Android launcher icons", () => {
  const dirs = readdirSync(RES).filter((d) => d.startsWith("mipmap-") && !d.includes("anydpi"));

  it("every density has all four icons at the right size", () => {
    expect(dirs.sort()).toEqual(Object.keys(DENSITY).map((d) => `mipmap-${d}`).sort());
    for (const dir of dirs) {
      const size = DENSITY[dir.replace("mipmap-", "")]!;
      for (const name of ["ic_launcher", "ic_launcher_round", "ic_launcher_foreground", "ic_launcher_background"]) {
        const file = join(RES, dir, `${name}.png`);
        expect(existsSync(file), file).toBe(true);
        expect(header(file), file).toMatchObject({ w: size, h: size });
      }
    }
  });

  it("the adaptive icon points at files that exist", () => {
    for (const xml of ["mipmap-anydpi-v26/ic_launcher.xml", "mipmap-anydpi-v26/ic_launcher_round.xml"]) {
      const text = readFileSync(join(RES, xml), "utf8");
      for (const [, name] of text.matchAll(/@mipmap\/(\w+)/g)) expect(existsSync(join(RES, "mipmap-xxxhdpi", `${name}.png`)), `${xml} ${name}`).toBe(true);
    }
  });

  it("the background layer is full bleed and bright; the round icon has transparent corners", async () => {
    for (const dir of dirs) {
      const { channels } = await sharp(join(RES, dir, "ic_launcher_background.png")).removeAlpha().stats();
      for (const c of channels) expect(c.min, dir).toBeGreaterThan(200);
    }
    const round = await sharp(join(RES, "mipmap-xxxhdpi/ic_launcher_round.png")).ensureAlpha().raw().toBuffer();
    expect(round[3]).toBe(0);
  });

  it("the foreground is the mark alone on transparency, inside the 66-unit safe circle once the 16.7% inset is applied", async () => {
    for (const dir of dirs) {
      const file = join(RES, dir, "ic_launcher_foreground.png");
      const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
      const size = info.width;
      const inset = size * 0.167;
      const inner = size - 2 * inset;
      /* Map a pixel of the file to the 108-unit layer the launcher masks. */
      const unit = (px: number) => ((inset + (px / size) * inner) / size) * 108;
      let seen = 0;
      let worst = 0;
      for (let y = 0; y < size; y++) {
        for (let x = 0; x < size; x++) {
          if (data[(y * size + x) * 4 + 3]! < 24) continue;
          seen++;
          worst = Math.max(worst, Math.hypot(unit(x + 0.5) - 54, unit(y + 0.5) - 54));
        }
      }
      expect(seen, dir).toBeGreaterThan(0);
      expect(data[3], `${dir} corner`).toBe(0);
      /* The guaranteed safe circle has a 33-unit radius. A pixel of slack for the antialiased edge. */
      expect(worst, dir).toBeLessThanOrEqual(33 + 108 / size);
    }
  });
});

describe("the Capacitor asset sources", () => {
  it("icon-only, icon-foreground and icon-background are 1024 squares; the foreground keeps its alpha", () => {
    for (const name of ["icon-only", "icon-foreground", "icon-background"]) expect(header(join(WEB, "assets", `${name}.png`)), name).toMatchObject({ w: 1024, h: 1024 });
    expect(header(join(WEB, "assets/icon-foreground.png")).colourType).toBe(6);
  });
});

describe("the Android notification icon", () => {
  const xml = readFileSync(join(RES, "drawable/ic_stat_vallo.xml"), "utf8");
  it("is white on transparent: only opaque white fills, a 24dp vector", () => {
    const fills = [...xml.matchAll(/android:fillColor="([^"]+)"/g)].map((m) => m[1]);
    expect(fills.length).toBeGreaterThan(0);
    expect(new Set(fills)).toEqual(new Set(["#FFFFFFFF"]));
    expect(xml).toContain('android:width="24dp"');
    expect(xml).toContain('android:height="24dp"');
    expect(xml).not.toMatch(/android:strokeColor|android:tint="#(?!FFFFFF)/);
  });
});

describe("the legacy launcher colour resource", () => {
  it("names a bright ground, not the old navy", () => {
    const xml = readFileSync(join(RES, "values/ic_launcher_background.xml"), "utf8");
    expect(xml).toMatch(/#FFFFFF/i);
  });
});
